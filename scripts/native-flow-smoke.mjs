// Native UI flow checks. Only file-picker answers are supplied by the harness;
// project operations and encoders are the real Rust/FFmpeg implementation.
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createHash } from 'node:crypto';
const [outputArg, address = 'http://127.0.0.1:9335'] = process.argv.slice(2);
if (!outputArg) throw new Error('Usage: node scripts/native-flow-smoke.mjs OUTPUT_DIR [CDP_URL]');
const output = resolve(outputArg); mkdirSync(output, { recursive: true });
const browser = await chromium.connectOverCDP(address);
const page = browser.contexts()[0].pages().find(p => /tauri|127\.0\.0\.1:1420/.test(p.url())); assert(page);
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.evaluate(() => {
  const mute = () => document.querySelectorAll('video,audio').forEach(v => { v.defaultMuted = true; v.muted = true; v.volume = 0; });
  document.addEventListener('play', mute, true); document.addEventListener('volumechange', mute, true);
  new MutationObserver(mute).observe(document, { childList: true, subtree: true }); mute();
  const original = window.__TAURI_INTERNALS__.invoke.bind(window.__TAURI_INTERNALS__);
  window.__monoPickerAnswer = null;
  window.__TAURI_INTERNALS__.invoke = (cmd, args, options) => cmd === 'plugin:dialog|save' || cmd === 'plugin:dialog|open' ? Promise.resolve(window.__monoPickerAnswer) : original(cmd, args, options);
});
const invoke = (command, args = {}) => page.evaluate(({ command, args }) => window.__TAURI_INTERNALS__.invoke(command, args), { command, args });
const answer = value => page.evaluate(value => { window.__monoPickerAnswer = value; }, value);
await page.getByRole('button', { name: /camera-a.mp4, starts/ }).first().click();
const x = page.getByRole('spinbutton', { name: 'Position X', exact: true });
await x.fill('-7.25'); await x.press('Tab'); await page.evaluate(() => document.activeElement?.blur());
await page.keyboard.press('Control+n');
const guard = page.getByRole('dialog', { name: 'Save your changes?', exact: true }); await guard.waitFor();
await guard.getByRole('button', { name: 'Save project', exact: true }).click();
await guard.getByText('Your project was not saved.', { exact: false }).waitFor();
assert.equal((await invoke('get_project')).clips.find(c => c.name === 'camera-a.mp4').transform.x, -7.25);
const projectPath = join(output, 'ui-saved.monocut'); await answer(projectPath);
await guard.getByRole('button', { name: 'Save project', exact: true }).click();
const create = page.getByRole('dialog', { name: 'New project', exact: true }); await create.waitFor();
assert(existsSync(projectPath)); await create.getByRole('button', { name: 'Cancel', exact: true }).click();
await page.evaluate(() => document.activeElement?.blur()); await answer(projectPath); await page.keyboard.press('Control+o');
await page.waitForFunction(() => document.querySelector('.header-project')?.textContent.includes('Mono Cut Validation') && !document.querySelector('.unsaved'));
assert.equal((await invoke('get_project')).clips.find(c => c.name === 'camera-a.mp4').transform.x, -7.25);
const videoPath = join(output, 'ui-export.mp4'); await answer(videoPath);
await page.getByRole('button', { name: 'Export', exact: true }).click();
const exportDialog = page.getByRole('dialog', { name: 'Export sequence', exact: true });
await exportDialog.getByRole('button', { name: 'Choose file & export', exact: true }).click();
await exportDialog.getByText('Export complete', { exact: true }).waitFor({ timeout: 120000 }); assert(existsSync(videoPath));
const digest = path => createHash('sha256').update(readFileSync(path)).digest('hex'); const before = digest(videoPath);
await exportDialog.getByRole('spinbutton', { name: 'Width', exact: true }).fill('3840');
await exportDialog.getByRole('spinbutton', { name: 'Height', exact: true }).fill('2160');
await exportDialog.getByRole('spinbutton', { name: 'Height', exact: true }).press('Tab');
await exportDialog.getByRole('button', { name: 'Export again', exact: true }).click();
await exportDialog.getByRole('button', { name: 'Cancel export', exact: true }).click();
await exportDialog.getByText('Export cancelled', { exact: true }).waitFor({ timeout: 30000 });
assert.equal(digest(videoPath), before, 'Cancelled replacement preserves previous complete export');
await exportDialog.getByRole('button', { name: 'Close', exact: true }).click();
await page.getByRole('button', { name: /camera-a.mp4, starts/ }).first().click();
await x.fill('-9.5'); await x.press('Tab');
await page.waitForFunction(() => window.__TAURI_INTERNALS__.invoke('get_project').then(p => p.clips.find(c => c.name === 'camera-a.mp4').transform.x === -9.5));
const report = { native: true, muted: true, filePickerAnswersSupplied: true, verified: ['cancelled save retains guard and edits', 'save proceeds only after real project file write', 'UI reopen retains negative decimal edit', 'UI export completes real encoder job', 'UI cancellation preserves previous complete export', 'unsaved autosave prepared for restart recovery'], errors };
writeFileSync(join(output, 'native-flow-validation.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2)); assert.equal(errors.length, 0); await browser.close();
