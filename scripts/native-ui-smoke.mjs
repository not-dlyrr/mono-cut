// UI checks run inside the native Tauri WebView2. All playback remains muted.
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
const [projectArg, outputArg, address = 'http://127.0.0.1:9335'] = process.argv.slice(2);
if (!projectArg || !outputArg) throw new Error('Usage: node scripts/native-ui-smoke.mjs PROJECT OUTPUT_DIR [CDP_URL]');
const output = resolve(outputArg); mkdirSync(output, { recursive: true });
const browser = await chromium.connectOverCDP(address);
const page = browser.contexts()[0].pages().find(p => /tauri|127\.0\.0\.1:1420/.test(p.url()));
assert(page, 'Native WebView2 page required');
const mute = () => {
  const apply = () => document.querySelectorAll('video,audio').forEach(v => { v.defaultMuted = true; v.muted = true; v.volume = 0; });
  document.addEventListener('play', apply, true); document.addEventListener('volumechange', apply, true);
  new MutationObserver(apply).observe(document, { childList: true, subtree: true }); apply();
};
await page.addInitScript(mute); await page.evaluate(mute);
const errors = []; page.on('pageerror', e => errors.push(e.message));
const screenshot = async name => { await page.waitForTimeout(250); await page.screenshot({ path: join(output, name) }); };
const invoke = (command, args = {}) => page.evaluate(({ command, args }) => window.__TAURI_INTERNALS__.invoke(command, args), { command, args });
await page.waitForFunction(() => window.__TAURI_INTERNALS__?.invoke);
await invoke('open_project', { path: resolve(projectArg) });
await page.evaluate(() => { localStorage.removeItem('mono-cut-mode'); localStorage.removeItem('mono-cut-tour-complete'); localStorage.setItem('mono-cut-theme', '"dark"'); });
await page.reload(); await page.waitForSelector('.timeline-clip');
if (await page.getByRole('button', { name: 'Keep current project' }).count()) await page.getByRole('button', { name: 'Keep current project' }).click();
assert.equal(await page.getByRole('combobox', { name: 'Editor mode' }).inputValue(), 'easy');
assert.equal(await page.locator('.monitor:visible').count(), 1);
await page.getByRole('button', { name: 'Next step', exact: true }).waitFor();
await screenshot('mono-cut-tutorial.png');
for (let i = 0; i < 6; i++) { await page.getByRole('button', { name: 'Next step', exact: true }).click(); await page.waitForTimeout(80); }
await page.getByRole('button', { name: 'Finish tutorial', exact: true }).click();
assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('mono-cut-tour-complete'))), true);
await page.getByRole('button', { name: 'Help', exact: true }).click();
await page.getByRole('button', { name: 'Restart tutorial', exact: true }).click();
await page.getByRole('button', { name: 'Next step', exact: true }).waitFor();
await page.keyboard.press('Escape'); assert.equal(await page.locator('.tour-card').count(), 0);
await page.reload(); await page.waitForSelector('.timeline-clip');
if (await page.getByRole('button', { name: 'Keep current project' }).count()) await page.getByRole('button', { name: 'Keep current project' }).click();
assert.equal(await page.getByRole('button', { name: 'Next step', exact: true }).count(), 0);
await page.getByRole('button', { name: /camera-a.mp4, starts/ }).first().click();
const clip = (await invoke('get_project')).clips.find(c => c.name === 'camera-a.mp4');
const x = page.getByRole('spinbutton', { name: 'Position X', exact: true });
await x.fill('-12.5'); await x.press('Tab');
await page.waitForFunction(id => window.__TAURI_INTERNALS__.invoke('get_project').then(p => p.clips.find(c => c.id === id).transform.x === -12.5), clip.id);
await page.evaluate(() => document.activeElement?.blur());
await page.keyboard.press('Control+n');
const guard = page.getByRole('dialog', { name: 'Save your changes?', exact: true });
await guard.waitFor(); await guard.getByRole('button', { name: 'Cancel', exact: true }).click();
assert.equal((await invoke('get_project')).clips.find(c => c.id === clip.id).transform.x, -12.5);
await page.getByRole('button', { name: 'Undo', exact: true }).click();
await page.waitForFunction(id => window.__TAURI_INTERNALS__.invoke('get_project').then(p => p.clips.find(c => c.id === id).transform.x === 0), clip.id);
await page.getByRole('button', { name: 'Play program', exact: true }).waitFor({ timeout: 120000 });
await page.waitForFunction(() => { const v = document.querySelector('[data-monitor="program"] video'); return v?.readyState >= 2 && !document.querySelector('[data-monitor="program"] .monitor-status'); }, null, { timeout: 120000 });
await page.keyboard.press('Space');
await page.getByRole('button', { name: 'Pause program', exact: true }).waitFor();
await page.getByRole('button', { name: 'Pause program', exact: true }).click();
await page.keyboard.press('Space');
await page.waitForFunction(() => !document.querySelector('[data-monitor="program"] video').paused);
await page.keyboard.press('k');
await page.waitForFunction(() => document.querySelector('[data-monitor="program"] video').paused);
assert(await page.locator('video').evaluateAll(vs => vs.every(v => v.muted && v.volume === 0)), 'Playback remains muted');
const program = page.locator('[data-monitor="program"] video');
await program.evaluate(async v => { await new Promise(r => { v.addEventListener('seeked', r, { once: true }); v.currentTime = 1; }); });
await screenshot('mono-cut-easy.png');
await page.getByRole('combobox', { name: 'Editor mode' }).selectOption('advanced');
assert.equal(await page.locator('.monitor:visible').count(), 2);
await screenshot('mono-cut-advanced.png');
await page.getByRole('combobox', { name: 'Editor mode' }).selectOption('easy');
await page.getByRole('button', { name: 'Appearance', exact: true }).click();
await page.getByRole('button', { name: 'Light', exact: true }).click(); await page.keyboard.press('Escape');
assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
await screenshot('mono-cut-light.png');
await page.getByRole('button', { name: 'Appearance', exact: true }).click();
await page.getByRole('button', { name: 'Dark', exact: true }).click(); await page.keyboard.press('Escape');
await page.getByRole('button', { name: 'Export', exact: true }).click();
const exportDialog = page.getByRole('dialog', { name: 'Export sequence', exact: true }); await exportDialog.waitFor();
await screenshot('mono-cut-export.png');
await exportDialog.getByRole('button', { name: 'Close', exact: true }).click();
for (const size of [{ width: 1280, height: 720 }, { width: 1920, height: 1080 }]) {
  await page.setViewportSize(size);
  await screenshot(`mono-cut-easy-${size.width}.png`);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Workspace fits viewport width');
}
const report = { native: true, muted: true, verified: ['Easy default and one monitor', 'all seven tutorial steps', 'Help restart and Escape', 'tutorial dismissal persistence', 'negative decimal property edit', 'unsaved Cancel retains edits', 'undo UI', 'Space/Pause/Space transport', 'keyboard stop', 'Advanced two monitors', 'light and dark Appearance', 'real export settings dialog'], errors };
writeFileSync(join(output, 'native-ui-validation.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2)); assert.equal(errors.length, 0);
await browser.close();
